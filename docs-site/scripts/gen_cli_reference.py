#!/usr/bin/env python3
"""Generate src/content/docs/reference/cli.md from `python -m hearthwork <command> --help`.

Commands are read from src/hearthwork/cli.py (its usage text and its dispatch).
Usage:  python docs-site/scripts/gen_cli_reference.py          write the file
        python docs-site/scripts/gen_cli_reference.py --check  exit 1 if the file is out of date
"""
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CLI = ROOT / "src" / "hearthwork" / "cli.py"
OUT = ROOT / "docs-site" / "src" / "content" / "docs" / "reference" / "cli.md"
HIDDEN = {"host", "statusline", "menu", "help", "version"}


def commands():
    text = CLI.read_text(encoding="utf-8")
    found = []

    def add(name):
        if name not in found and name not in HIDDEN:
            found.append(name)

    usage = text.split('"""')[1]
    for m in re.finditer(r"^\s+hearthwork ([a-z]+)", usage, re.M):
        add(m.group(1))
    main_src = text[text.index("def main("):]
    for m in re.finditer(r'command == "([a-z]+)"', main_src):
        add(m.group(1))
    for m in re.finditer(r'command in \(([^)]*)\)', main_src):
        for n in re.findall(r'"([a-z]+)"', m.group(1)):
            add(n)
    return [c for c in found if c not in agents()]


def agents():
    """Agent launchers: `hearthwork <agent> --help` is passed on to the agent itself, so they share one section."""
    src = (CLI.parent / "harnesses.py").read_text(encoding="utf-8")
    return re.findall(r'^    "([a-z]+)": \{"title"', src, re.M)


def help_text(cmd):
    env = dict(os.environ, PYTHONPATH=str(ROOT / "src"), PYTHONIOENCODING="utf-8", COLUMNS="100", NO_COLOR="1")
    r = subprocess.run([sys.executable, "-m", "hearthwork", cmd, "--help"], capture_output=True, text=True,
                       encoding="utf-8", env=env, cwd=str(ROOT), timeout=60)
    if r.returncode != 0:
        sys.exit(f"`hearthwork {cmd} --help` exited {r.returncode}: {r.stderr.strip()}")
    return (r.stdout or r.stderr).replace("\r\n", "\n").rstrip()


def build():
    out = ["---", "title: Command reference",
           "description: Every Hearthwork command and its --help output, generated from the code.", "---", "",
           "{/* Generated by docs-site/scripts/gen_cli_reference.py. Do not edit by hand. */}", "",
           "This page is generated from `hearthwork <command> --help`, so it always matches the installed version. "
           "Run `hearthwork --help` for the short list.", ""]
    out = [l for l in out]
    names = agents()
    out += [f"## {', '.join(names)}", "",
            "Each agent launcher passes every argument after its name to the agent itself, so `--help` there shows "
            "the agent's own help. Hearthwork's own flag is `--dry-run`, and only as the first argument.", "",
            "```text", f"hearthwork <{'|'.join(names)}> [--dry-run] [agent arguments]", "```", ""]
    for cmd in commands():
        out += [f"## {cmd}", "", "```text", help_text(cmd), "```", ""]
    # .md (not .mdx) so the comment line must be an HTML comment
    return "\n".join(out).replace("{/* Generated by docs-site/scripts/gen_cli_reference.py. Do not edit by hand. */}",
                                  "<!-- Generated by docs-site/scripts/gen_cli_reference.py. Do not edit by hand. -->") + "\n"


def main():
    new = build()
    if "--check" in sys.argv:
        old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if old.replace("\r\n", "\n") != new:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run: python docs-site/scripts/gen_cli_reference.py")
            return 1
        print("CLI reference is up to date.")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(new, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
